"""Write the paper's LaTeX tables from the results (stdlib only).

    python3 paper/make_tables.py

Reads results/summary_tasks.csv, results/summary_runs.csv, projects/*/runs/*/s*/final_scores.json,
results/robustness/baselines.csv, results/stats_tasks.csv and results/stats_pooled.json;
writes paper/tables/*.tex.
Re-run after core/report.py / core/stats.py whenever results change; never edit the .tex tables by hand.

Robustness tables read results/stats_tasks.csv, results/stats_pooled.json and
results/robustness/confounds.csv as written by core/stats.py and core/confounds.py: p-values there
already use the (k+1)/(n+1) convention and are Holm-adjusted across the 12 tasks. Per-task claims use
the hierarchical bootstrap (splits, loop runs, subjects); ^ marks tasks that are significant only
conditionally on the fitted models (subject bootstrap).
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "paper" / "tables"

# display order and names (project, task) -> (modality, task label)
TASKS = [
    ("eeg_psych", "abnormal_tuab", "EEG", "Abnormal EEG (TUAB)"),
    ("eeg_psych", "mdd_tdbrain", "EEG", "MDD (TDBRAIN)"),
    ("eeg_psych", "adhd_tdbrain", "EEG", "ADHD (TDBRAIN)"),
    ("eeg_psych", "sz_aseeg", "EEG", "Schizophrenia (ASEEG)"),
    ("neonatal_seizure", "helsinki", "EEG", "Neonatal seizure (Helsinki)"),
    ("fmri_connectivity", "autism_abide", "fMRI", "Autism (ABIDE I)$^\\dagger$"),
    ("fmri_connectivity", "adhd_adhd200", "fMRI", "ADHD (ADHD-200)$^{\\dagger\\S}$"),
    ("microbiome", "crc_baxter", "16S", "CRC (Baxter)"),
    ("microbiome", "ibd_pooled", "16S", "IBD (4 studies)$^\\dagger$"),
    ("proteomics_ad", "plasma_ad", "Proteomics", "AD, plasma"),
    ("proteomics_ad", "csf_ad", "Proteomics", "AD, CSF$^\\dagger$"),
    ("drug_response", "prism_auc", "Expression", "Drug response (PRISM)$^\\ddagger$"),
]
EXT_NAMES = {
    "tuab_official_eval": "TUAB official eval",
    "mumtaz": "Mumtaz 2016",
    "msu": "MSU",
    "repod": "RepOD",
    "crc_zeller": "Zeller",
    "crc_zackular": "Zackular",
    "crc_xiang": "Xiang",
    "crc_zhao": "Zhao",
}
LABEL = {(p, t): name for p, t, _, name in TASKS}


def read_csv(name):
    with open(ROOT / "results" / name) as f:
        return list(csv.DictReader(f))


def f3(x):
    return f"{float(x):.3f}"


def signed(x, nd=3):
    x = float(x)
    s = f"{x:+.{nd}f}"
    return s.replace("-", "$-$")


def pval(p):
    p = float(p)
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def write(name, lines):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text("\n".join(lines) + "\n")
    print("wrote", OUT / name)


def main_table():
    rows = {(r["project"], r["task"]): r for r in read_csv("summary_tasks.csv")}
    L = [
        "% generated by paper/make_tables.py from results/summary_tasks.csv -- do not edit",
        "\\begin{tabular}{llcccccc}",
        "\\toprule",
        " & & \\multicolumn{2}{c}{Dev (5-fold CV)} & \\multicolumn{2}{c}{Held-out Eval} & & \\\\",
        "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}",
        "Modality & Task & seed & champion & seed & champion & Eval gain (mean $\\pm$ sd) & improved / sig. \\\\",
        "\\midrule",
    ]
    prev = None
    for p, t, mod, name in TASKS:
        r = rows[(p, t)]
        if prev is not None and mod != prev:
            L.append("\\addlinespace")
        L.append(
            f"{mod if mod != prev else ''} & {name} & {f3(r['dev_seed'])} & {f3(r['dev_champion'])} & "
            f"{f3(r['eval_seed'])} & {f3(r['eval_champion'])} & "
            f"{signed(r['eval_gain_mean'])} $\\pm$ {float(r['eval_gain_sd']):.3f} & "
            f"{r['splits_improved']}/{r['n_splits']} \\;/\\; {r['splits_sig_p05']}/{r['n_splits']} \\\\"
        )
        prev = mod
    L += ["\\bottomrule", "\\end{tabular}"]
    write("main_results.tex", L)


def per_run_table():
    runs = {(r["project"], r["task"], r["seed"]): r for r in read_csv("summary_runs.csv")}
    L = [
        "% generated by paper/make_tables.py from results/summary_runs.csv -- do not edit",
        "\\begin{tabular}{lcccccccc}",
        "\\toprule",
        "Task & split & rounds & kept & failed & Dev gain & Eval gain & 95\\% CI & $p$ (one-sided) \\\\",
        "\\midrule",
    ]
    for i, (p, t, _, name) in enumerate(TASKS):
        if i:
            L.append("\\addlinespace")
        for s in ("1", "2", "3"):
            r = runs[(p, t, s)]
            failed = int(r["failed_timeout"]) + int(r["failed_crash"])
            L.append(
                f"{name if s == '1' else ''} & {s} & {r['rounds']} & {r['kept']} & {failed} & "
                f"{signed(r['dev_gain'])} & {signed(r['eval_gain'])} & "
                f"[{signed(r['ci_lo'])}, {signed(r['ci_hi'])}] & {pval(r['p_one_sided'])} \\\\"
            )
    L += ["\\bottomrule", "\\end{tabular}"]
    write("per_run.tex", L)


def external_table():
    L = [
        "% generated by paper/make_tables.py from projects/*/runs/*/s*/final_scores.json -- do not edit",
        "\\begin{tabular}{llccccc}",
        "\\toprule",
        "Task & External set & split & seed & champion & gain & 95\\% CI \\\\",
        "\\midrule",
    ]
    first = True
    for p, t, _, name in TASKS:
        per_ext = {}
        for s in (1, 2, 3):
            f = ROOT / "projects" / p / "runs" / t / f"s{s}" / "final_scores.json"
            ext = json.loads(f.read_text()).get("external") or {}
            for k, v in ext.items():
                per_ext.setdefault(k, []).append((s, v))
        if not per_ext:
            continue
        if not first:
            L.append("\\addlinespace")
        first = False
        task_cell = name
        for k, vals in per_ext.items():
            ext_cell = EXT_NAMES.get(k, k)
            for s, v in vals:
                lo, hi = v["bootstrap"]["ci95"]
                L.append(
                    f"{task_cell} & {ext_cell} & {s} & {f3(v['seed'])} & {f3(v['champion'])} & "
                    f"{signed(v['gain'])} & [{signed(lo)}, {signed(hi)}] \\\\"
                )
                task_cell = ext_cell = ""
    L += ["\\bottomrule", "\\end{tabular}"]
    write("external.tex", L)


# ---------------------------------------------------------------- robustness tables
ARMS = [("seed", "Seed"), ("oneshot", "One-shot"), ("bestof20", "Best-of-20"),
        ("optuna", "Optuna"), ("loop", "Loop")]
# pooled sensitivity rows shown in the paper (labels as written by core/stats.py)
SENSITIVITY = [("TDBRAIN counted as one dataset", "TDBRAIN as one dataset"),
               ("without TDBRAIN MDD + ADHD", "without TDBRAIN"),
               ("without ADHD-200", "without ADHD-200"),
               ("without TDBRAIN MDD + ADHD and ADHD-200", "without TDBRAIN and ADHD-200")]


def ptex(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def stats_rows():
    """{comparison: {task: row}} from results/stats_tasks.csv."""
    by = {}
    for r in read_csv("stats_tasks.csv"):
        by.setdefault(r["comparison"], {})[r["task"]] = r
    return by


def gain_cell(r):
    """Gain, bold if Holm-significant with the hierarchical bootstrap; ^ if significant only
    conditionally on the fitted models (subject bootstrap)."""
    g = signed(r["gain"])
    if float(r["p_hier_holm"]) < 0.05:
        return f"\\textbf{{{g}}}"
    if float(r["p_holm"]) < 0.05:
        return f"{g}$^\\wedge$"
    return g


def eval_means():
    acc = {}
    for r in read_csv("robustness/baselines.csv"):
        acc.setdefault((r["task"], r["arm"]), []).append(float(r["eval"]))
    return {k: sum(v) / len(v) for k, v in acc.items()}


def arm_cells(means, t):
    vals = [means[(t, a)] for a, _ in ARMS]
    best = max(vals[1:])
    return [f3(v) if i == 0 or v < best else f"\\textbf{{{f3(v)}}}" for i, v in enumerate(vals)]


def baselines_table():
    means = eval_means()
    L = [
        "% generated by paper/make_tables.py from results/robustness/baselines.csv -- do not edit",
        "\\begin{tabular}{l" + "c" * len(ARMS) + "}",
        "\\toprule",
        "Task & " + " & ".join(n for _, n in ARMS) + " \\\\",
        "\\midrule",
    ]
    for p, t, _, name in TASKS:
        L.append(f"{name} & " + " & ".join(arm_cells(means, t)) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write("baselines.tex", L)


def stats_table():
    by = stats_rows()
    comps = [("seed->loop", "Loop $-$ seed"), ("seed->optuna", "Optuna $-$ seed"),
             ("bestof20->loop", "Loop $-$ best-of-20"), ("optuna->loop", "Loop $-$ Optuna")]
    L = [
        "% generated by paper/make_tables.py from results/stats_tasks.csv -- do not edit",
        "\\begin{tabular}{l" + "rrr" * len(comps) + "}",
        "\\toprule",
        "& " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{n}}}" for _, n in comps) + " \\\\",
        "".join(f"\\cmidrule(lr){{{2 + 3 * i}-{4 + 3 * i}}}" for i in range(len(comps))),
        "Task" + " & gain & hier. & subj." * len(comps) + " \\\\",
        "\\midrule",
    ]
    for p, t, _, name in TASKS:
        cells = []
        for c, _ in comps:
            r = by[c][t]
            cells += [gain_cell(r), ptex(float(r["p_hier_holm"])), ptex(float(r["p_holm"]))]
        L.append(f"{name} & " + " & ".join(cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write("stats.tex", L)


def combined_table():
    """Main-text table: Eval per arm, loop gain vs seed and vs Optuna (Holm, hierarchical), splits improved."""
    means = eval_means()
    by = stats_rows()
    L = [
        "% generated by paper/make_tables.py from results/robustness/baselines.csv and stats_tasks.csv -- do not edit",
        "\\begin{tabular}{l" + "c" * len(ARMS) + "rrrrc}",
        "\\toprule",
        " & \\multicolumn{5}{c}{Held-out Eval (mean of 3 splits)} & \\multicolumn{2}{c}{Loop $-$ seed}"
        " & \\multicolumn{2}{c}{Loop $-$ Optuna} & \\\\",
        "\\cmidrule(lr){2-6}\\cmidrule(lr){7-8}\\cmidrule(lr){9-10}",
        "Task & " + " & ".join(n for _, n in ARMS)
        + " & gain & $p_\\text{Holm}$ & gain & $p_\\text{Holm}$ & splits $\\uparrow$ \\\\",
        "\\midrule",
    ]
    for p, t, _, name in TASKS:
        cells = arm_cells(means, t)
        for c in ("seed->loop", "optuna->loop"):
            r = by[c][t]
            cells += [gain_cell(r), ptex(float(r["p_hier_holm"]))]
        up = sum(float(x) > 0 for x in by["seed->loop"][t]["split_gains"].split())
        L.append(f"{name} & " + " & ".join(cells) + f" & {up}/3 \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write("combined.tex", L)


def pooled_table():
    pooled = json.loads((ROOT / "results" / "stats_pooled.json").read_text())
    comps = [("seed->loop", "Loop vs.\\ seed"), ("seed->optuna", "Optuna vs.\\ seed"),
             ("seed->bestof20", "Best-of-20 vs.\\ seed"), ("seed->oneshot", "One-shot vs.\\ seed"),
             ("optuna->loop", "Loop vs.\\ Optuna"), ("bestof20->loop", "Loop vs.\\ best-of-20"),
             ("oneshot->loop", "Loop vs.\\ one-shot")]
    L = [
        "% generated by paper/make_tables.py from results/stats_pooled.json -- do not edit",
        "\\begin{tabular}{lcccccc}",
        "\\toprule",
        "Comparison & $k$ & mean gain & 95\\% CI & $p$ & random effects [95\\% CI] & $I^2$ \\\\",
        "\\midrule",
    ]
    for c, name in comps:
        s = pooled[c]
        lo, hi = s["ci95_equal"]
        rlo, rhi = s["ci95"]
        L.append(f"{name} & {s['k']} & {signed(s['mean_equal'])} & [{signed(lo)}, {signed(hi)}] & "
                 f"{ptex(s['p_equal'])} & {signed(s['random_effects'])} [{signed(rlo)}, {signed(rhi)}] & "
                 f"{100 * s['I2']:.0f}\\% \\\\")
    L += ["\\midrule",
          "\\multicolumn{7}{l}{\\emph{Sensitivity of the equal-weight mean}} \\\\"]
    for c, name in (("seed->loop", "Loop vs.\\ seed"), ("optuna->loop", "Loop vs.\\ Optuna")):
        sens = {x["label"]: x for x in pooled[c]["sensitivity"]}
        for label, short in SENSITIVITY:
            x = sens[label]
            L.append(f"{name}, {short} & {x['k']} & {signed(x['mean'])} & "
                     f"[{signed(x['ci95'][0])}, {signed(x['ci95'][1])}] & {ptex(x['p'])} & & \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write("pooled.tex", L)


def confounds_table():
    rows = read_csv("robustness/confounds.csv")
    names = {"adhd_adhd200": "ADHD (ADHD-200)$^\\dagger$", "autism_abide": "Autism (ABIDE I)$^\\dagger$",
             "mdd_tdbrain": "MDD (TDBRAIN)", "adhd_tdbrain": "ADHD (TDBRAIN)"}
    acc = {}
    for r in rows:
        acc.setdefault((r["task"], r["arm"]), []).append(r)
    mean = lambda rs, k: sum(float(r[k]) for r in rs) / len(rs)
    L = [
        "% generated by paper/make_tables.py from results/robustness/confounds.csv -- do not edit",
        "\\begin{tabular}{llcccc}",
        "\\toprule",
        "Task & arm & AUROC & age+sex only & adjusted for age+sex & LR test $p<0.05$ (splits) \\\\",
        "\\midrule",
    ]
    for t, name in names.items():
        for i, arm in enumerate(("seed", "champion")):
            rs = acc[(t, arm)]
            sig = sum(float(r["lr_p"]) < 0.05 for r in rs)
            L.append(f"{name if i == 0 else ''} & {arm} & {f3(mean(rs, 'auc_reported'))} & "
                     f"{f3(mean(rs, 'auc_demographics_only'))} & {f3(mean(rs, 'auc_adjusted'))} & {sig}/{len(rs)} \\\\")
    L += ["\\bottomrule", "\\end{tabular}"]
    write("confounds.tex", L)


